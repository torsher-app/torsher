import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

/**
 * Строки экрана адреса — раздел `shell` из `@torsher/i18n`, тот же, что у
 * обёртки webOS. Android читает их из ресурсов, поэтому `pnpm strings`
 * переписывает `strings.xml` каталогов `values`, а тест сверяет их с JSON.
 */

const LOCALES = [
  { locale: 'en_US', dir: 'values' },
  { locale: 'ru_RU', dir: 'values-ru' },
]

const root = new URL('../', import.meta.url)

interface Messages {
  [key: string]: string | Messages
}

function snake(key: string) {
  return key.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)
}

function flatten(messages: Messages, prefix: string): [string, string][] {
  return Object.entries(messages).flatMap(([key, value]) => {
    const name = `${prefix}_${snake(key)}`
    return typeof value === 'string' ? [[name, value]] : flatten(value, name)
  })
}

/**
 * Плейсхолдеры `{address}` становятся `%1$s` в порядке появления: у строк
 * обёртки он один, Kotlin передаёт значение позиционно.
 */
export function androidString(value: string) {
  const names: string[] = []
  const text = value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, '\\\'')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/%/g, '%%')
    .replace(/^([@?])/, '\\$1')

  return text.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!names.includes(name))
      names.push(name)
    return `%${names.indexOf(name) + 1}$s`
  })
}

export function stringsXml(shell: Messages) {
  const lines = flatten(shell, 'shell').map(
    ([name, value]) =>
      `  <string name="${name}">${androidString(value)}</string>`,
  )

  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by `pnpm strings` from @torsher/i18n (shell.*): do not edit -->',
    '<resources>',
    ...lines,
    '</resources>',
    '',
  ].join('\n')
}

export function shellMessages(locale: string): Messages {
  const file = fileURLToPath(
    new URL(`../../packages/i18n/src/locales/${locale}/ui.json`, root),
  )
  return (JSON.parse(readFileSync(file, 'utf8')) as { shell: Messages }).shell
}

export function resourceFiles() {
  return LOCALES.map(({ locale, dir }) => ({
    path: fileURLToPath(new URL(`app/src/main/res/${dir}/strings.xml`, root)),
    content: stringsXml(shellMessages(locale)),
  }))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const { path, content } of resourceFiles()) writeFileSync(path, content)
}
